bool looksLikeJpeg(const std::vector<uint8_t> &j) {
    return j.size() > 4 && j[0] == 0xff && j[1] == 0xd8;
}

std::vector<uint8_t> addHuffmanTables(const std::vector<uint8_t> &j) {
    bool hasDht;
    long sos = findSos(j, hasDht);
    if (sos < 0 || hasDht) return j;
    const auto &t = dht();
    std::vector<uint8_t> out;
    out.reserve(j.size() + t.size());
    out.insert(out.end(), j.begin(), j.begin() + sos);
    out.insert(out.end(), t.begin(), t.end());
    out.insert(out.end(), j.begin() + sos, j.end());
    return out;
}

std::string hex(const std::vector<uint8_t> &d, size_t max) {
    std::string s;
    char b[4];
    for (size_t i = 0; i < d.size() && i < max; i++) {
        snprintf(b, sizeof b, "%02x ", d[i]);
        s += b;
    }
    if (!s.empty()) s.pop_back();
    return s;
}

bool decode(IWICImagingFactory *f, const std::vector<uint8_t> &j,
            std::vector<uint8_t> &pixels, int &w, int &h) {
    if (!f || j.empty()) return false;
    IWICStream *st = nullptr;
    IWICBitmapDecoder *dec = nullptr;
    IWICBitmapFrameDecode *fr = nullptr;
    IWICFormatConverter *cv = nullptr;
    bool ok = false;
    do {
        if (FAILED(f->CreateStream(&st))) break;
        if (FAILED(st->InitializeFromMemory((BYTE *) j.data(), (DWORD) j.size()))) break;
        if (FAILED(f->CreateDecoderFromStream(st, nullptr, WICDecodeMetadataCacheOnDemand, &dec))) break;
        if (FAILED(dec->GetFrame(0, &fr))) break;
        UINT uw = 0, uh = 0;
        if (FAILED(fr->GetSize(&uw, &uh)) || uw == 0 || uh == 0 || uw > 4096 || uh > 4096) break;
        if (FAILED(f->CreateFormatConverter(&cv))) break;
        if (FAILED(cv->Initialize(fr, GUID_WICPixelFormat32bppBGR, WICBitmapDitherTypeNone,
                                  nullptr, 0.0, WICBitmapPaletteTypeCustom))) break;
        pixels.resize((size_t) uw * uh * 4);
        if (FAILED(cv->CopyPixels(nullptr, uw * 4, (UINT) pixels.size(), pixels.data()))) break;
        w = (int) uw;
        h = (int) uh;
        ok = true;
    } while (false);
    release(cv);
    release(fr);
    release(dec);
    release(st);
    return ok;
}

