template <size_t NB, size_t NV>
void table(std::vector<uint8_t> &o, int cls, const uint8_t (&bits)[NB], const uint8_t (&vals)[NV]) {
    o.push_back((uint8_t) cls);
    o.insert(o.end(), bits, bits + NB);
    o.insert(o.end(), vals, vals + NV);
}

std::vector<uint8_t> buildDht() {
    std::vector<uint8_t> body;
    table(body, 0x00, DC_LUM_BITS, DC_VALS);
    table(body, 0x10, AC_LUM_BITS, AC_LUM_VALS);
    table(body, 0x01, DC_CHR_BITS, DC_VALS);
    table(body, 0x11, AC_CHR_BITS, AC_CHR_VALS);
    size_t len = body.size() + 2;
    std::vector<uint8_t> o = {0xff, 0xc4, (uint8_t) (len >> 8), (uint8_t) (len & 0xff)};
    o.insert(o.end(), body.begin(), body.end());
    return o;
}

const std::vector<uint8_t> &dht() {
    static const std::vector<uint8_t> t = buildDht();
    return t;
}

// Walks the JPEG header. Returns the offset of the SOS marker, or -1.
long findSos(const std::vector<uint8_t> &j, bool &foundDht) {
    foundDht = false;
    if (j.size() < 4 || j[0] != 0xff || j[1] != 0xd8) return -1;
    size_t i = 2;
    while (i + 4 <= j.size()) {
        if (j[i] != 0xff) return -1;
        int m = j[i + 1];
        if (m == 0xff) { i++; continue; }                          // fill byte
        if (m == 0x01 || (m >= 0xd0 && m <= 0xd8)) { i += 2; continue; }
        if (m == 0xc4) foundDht = true;
        if (m == 0xda) return (long) i;
        int seg = (j[i + 2] << 8) | j[i + 3];
        if (seg < 2) return -1;
        i += 2 + (size_t) seg;
    }
    return -1;
}

